// Draws the Prism logo (assets/prism-mark.svg) from the 3D pyramid in assets/prism-pyramid.json, so the logo and the
// 3D model are the same object. Faces, gradients and colours follow the original artwork (design/legacy-logo/):
// front face, left and right faces, the base seen through the glass (the lower band, split where the front-left edge
// crosses it), and the thin light edge along the front-left ridge. `node scripts/draw-mark.cjs [out.svg]`
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),cam=JSON.parse(fs.readFileSync(path.join(root,'assets/prism-pyramid.json'),'utf8'));
// Pyramid corners (z up, base side 1): L back-left, F front-left, R front-right, Q back-right, A the tip.
const corners={L:[-.5,.5,0],F:[-.5,-.5,0],R:[.5,-.5,0],Q:[.5,.5,0],A:[0,0,cam.height]};
function project([x,y,z]){const r=cam.rotation,t=cam.translation,c=[0,1,2].map(i=>r[i][0]*x+r[i][1]*y+r[i][2]*z+t[i]);return [512+cam.focal*c[0]/c[2],512+cam.focal*c[1]/c[2]];}
const p=Object.fromEntries(Object.entries(corners).map(([k,v])=>[k,project(v)]));
// Where the front-left ridge (A–F) crosses the back edge of the base (L–Q), seen through the glass.
function cross([a,b],[c,d]){const r=[b[0]-a[0],b[1]-a[1]],s=[d[0]-c[0],d[1]-c[1]],den=r[0]*s[1]-r[1]*s[0],t=((c[0]-a[0])*s[1]-(c[1]-a[1])*s[0])/den;return [a[0]+r[0]*t,a[1]+r[1]*t];}
const P=cross([p.A,p.F],[p.L,p.Q]),G=[p.F[0]+(p.R[0]-p.F[0])*.612,p.F[1]+(p.R[1]-p.F[1])*.612];
// The light edge along A–F: the band starts a few pixels along the base edges, as in the original artwork.
const along=(a,b,px)=>{const d=Math.hypot(b[0]-a[0],b[1]-a[1]);return [a[0]+(b[0]-a[0])*px/d,a[1]+(b[1]-a[1])*px/d];},Fb=along(p.F,p.R,12),Pb=along(P,p.Q,10);
const poly=(cls,pts)=>`<polygon class="${cls}" points="${pts.map(([x,y])=>x.toFixed(2)+' '+y.toFixed(2)).join(' ')}"/>`;
const legacy=fs.readFileSync(path.join(root,'design/legacy-logo/prism-mark.svg'),'utf8'),defs=legacy.match(/<defs>[\s\S]*?<\/defs>/)[0];
const svg=`<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024"><!-- Generated by scripts/draw-mark.cjs from assets/prism-pyramid.json. -->
  ${defs}
  <g id="Background">
    <rect class="cls-1" width="1024" height="1024"/>
    <g>
      ${poly('cls-5',[p.Q,p.A,p.F,Fb,Pb])}
      ${poly('cls-4',[Pb,p.Q,G,Fb])}
      ${poly('cls-3',[p.A,P,p.L])}
      ${poly('cls-7',[p.R,G,p.Q])}
      ${poly('cls-6',[P,p.F,p.L])}
      ${poly('cls-2',[p.R,p.Q,p.A])}
    </g>
  </g>
</svg>
`;
const out=path.resolve(process.argv[2]||path.join(root,'assets/prism-mark.svg'));fs.writeFileSync(out,svg);
console.log('wrote',out,JSON.stringify(Object.fromEntries(Object.entries({...p,P,G}).map(([k,[x,y]])=>[k,[+x.toFixed(1),+y.toFixed(1)]]))));
